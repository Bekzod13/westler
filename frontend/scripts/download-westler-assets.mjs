/**
 * Downloads Figma MCP asset URLs from lib/westler-assets.ts into public/westler/
 * and rewrites lib/westler-assets.ts to use local /westler/* paths.
 *
 * Run: node scripts/download-westler-assets.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const assetsFile = path.join(root, "lib/westler-assets.ts");
const outDir = path.join(root, "public/westler");

const extByMime = {
  "image/svg+xml": "svg",
  "image/png": "png",
  "image/jpeg": "jpg",
  "image/jpg": "jpg",
  "image/webp": "webp",
  "image/gif": "gif",
};

function parseAssets(ts) {
  const re = /export const (\w+) =\s*"([^"]+)"/g;
  const list = [];
  let m;
  while ((m = re.exec(ts)) !== null) {
    list.push({ name: m[1], url: m[2] });
  }
  return list;
}

async function main() {
  const source = fs.readFileSync(assetsFile, "utf8");
  const entries = parseAssets(source);
  if (entries.length === 0) {
    console.error("No export const ... = url found in westler-assets.ts");
    process.exit(1);
  }

  fs.mkdirSync(outDir, { recursive: true });

  const lines = [
    "/** Local assets under /public/westler — generated by scripts/download-westler-assets.mjs */",
    "",
  ];

  let downloaded = 0;
  for (const { name, url } of entries) {
    if (!url.startsWith("http")) {
      lines.push(`export const ${name} = "${url}";`);
      continue;
    }
    process.stdout.write(`Fetching ${name}... `);
    const res = await fetch(url);
    if (!res.ok) {
      console.error(`\nFailed ${name}: ${res.status} ${res.statusText}`);
      process.exit(1);
    }
    const mime = (res.headers.get("content-type") || "")
      .split(";")[0]
      .trim()
      .toLowerCase();
    const ext = extByMime[mime] || "bin";
    const filename = `${name}.${ext}`;
    const buf = Buffer.from(await res.arrayBuffer());
    fs.writeFileSync(path.join(outDir, filename), buf);
    const publicPath = `/westler/${filename}`;
    lines.push(`export const ${name} = "${publicPath}";`);
    downloaded += 1;
    console.log(`${buf.length} bytes (${mime} -> .${ext})`);
  }

  lines.push("");
  fs.writeFileSync(assetsFile, lines.join("\n"));
  if (downloaded > 0) {
    console.log(
      `\nDownloaded ${downloaded} files to public/westler/ and updated lib/westler-assets.ts`,
    );
  } else {
    console.log("\nNo remote URLs in westler-assets.ts (already local).");
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
